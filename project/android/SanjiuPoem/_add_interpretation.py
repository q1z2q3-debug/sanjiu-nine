def inject(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    n = 0
    for obj in data:
        t = obj.get("title", "")
        if t in INTERPRETATIONS:
            obj["interpretation"] = INTERPRETATIONS[t]
            n += 1
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    return n, len(data)

