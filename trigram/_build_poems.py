for r in recs:
    if r["age"] != cur:
        cur = r["age"]
        md.append("")
        md.append("## " + cur)
        md.append("")
    md.append("### " + r["title"] + " · " + r["op"])
    md.append("")
    md.append("```")
    md.append(r["text"])
    md.append("```")
    md.append("")
