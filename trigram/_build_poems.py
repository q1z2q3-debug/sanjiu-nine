recs = []
for o in gua:
    k = (o["age"], o["op"])
    title, text = POEMS[k]
    recs.append({**o, "title": title, "text": text})

with open("chuangzuo_20.json", "w", encoding="utf-8") as f:
    json.dump(recs, f, ensure_ascii=False, indent=1)

md = []
