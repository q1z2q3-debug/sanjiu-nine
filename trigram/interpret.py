def coordinate(gua):
    """从卦确定性输出 9 维解读坐标系（可复现，作为赏析的出处基座）。"""
    return {AXIS[i]: COORD_SHORT[(i + 1, v)] for i, v in enumerate(gua)}


def _slot_sents(gua, slot):
    """取某槽位该爻位对应句子。"""
    idx = {"意象": [2, 7, 8, 3], "手法": [4, 5, 6], "情旨": [1], "立意": [9]}[slot]
    out = []
    for pos in idx:
        v = gua[pos - 1]
        out.append(RULES[(slot, pos, v)])
    return out

def interpret(gua, op="本卦"):
    """卦(9维列表) + op → 一段人类语言解读。确定性、可复现。"""
    opener = OP_OPENERS.get(op, OP_OPENERS["本卦"])
    parts = []

    # 意象槽：以"意象+境界"为引，接意脉与情感
    sent = _slot_sents(gua, "意象")
    img, jing, yimai, qing = sent[3], sent[2], sent[1], sent[0]
    parts.append("全诗以{意象}起笔，营造出{境界}的韵致；其间{意脉}，读来{情感}。".format(
        **{"意象": img, "境界": jing, "意脉": yimai, "情感": qing}))

    # 手法槽
    yong, yin, xiu = _slot_sents(gua, "手法")
    parts.append("在表达上，{用典}；{音律}，{修辞}，足见匠心。".format(
        **{"用典": yong, "音律": yin, "修辞": xiu}))

    # 情旨槽
    zz = _slot_sents(gua, "情旨")[0]
    parts.append("其情于{主旨}处见深浅，全篇托物寓情，含而不尽。".format(**{"主旨": zz}))

    # 立意槽
    ly = _slot_sents(gua, "立意")[0]
    parts.append("落笔在{立意}之处，令全篇既见当下之趣，又余味不尽。".format(**{"立意": ly}))

    return opener + "".join(parts)


